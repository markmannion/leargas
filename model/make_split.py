"""M1: drawing-level held-out split (contract C1).

Splits by drawing *group* (see common.group_key), never by question, so no drawing, twin file or
sibling view of the same IFC model appears in both train and eval.

  python -m model.make_split            # writes data/splits/heldout_drawings.txt + split_summary.json

Rules
- ~5% of drawing groups per source, stratified by the set of question types a drawing has
  (so e.g. swiss drawings with and without bathtub questions are both represented), seed 1337.
- Small sources get a floor so the eval isn't empty: ifc_models and ifc_bench hold out at least
  3 models each.
- opening_design (3 schedule sheets, 64 questions) is held out entirely: nobody trains on it,
  it is pure eval for Harry's PDF schedule engine.
- Unlabelled sources (habs, finna, europeana, wikimedia) have no questions and are not listed;
  nobody trains on them. The judge set's drawings from them are listed at the bottom anyway.

heldout_drawings.txt lists every file on disk that belongs to a held-out group (pdf, dxf, png,
svg, ifc twins), one dataset-relative path per line ('data/...'). Use common.is_heldout(path)
to test any path; it normalises twins and sibling views.
"""
from __future__ import annotations

import argparse
import collections
import json
import math
import random

from .common import (
    DATASET_ROOT,
    HELDOUT_PATH,
    SPLITS_DIR,
    group_key,
    load_questions,
    source_of,
)

SEED = 1337
FRACTION = 0.05
MIN_GROUPS = {"ifc_models": 3, "ifc_bench": 3}
ALL_HELDOUT = {"opening_design"}


def choose_heldout(questions: list[dict], fraction: float = FRACTION, seed: int = SEED) -> set[str]:
    groups_by_source: dict[str, dict[str, set[str]]] = collections.defaultdict(lambda: collections.defaultdict(set))
    for q in questions:
        groups_by_source[source_of(q["path"])][group_key(q["path"])].add(q["type"])

    rng = random.Random(seed)
    heldout: set[str] = set()
    for src in sorted(groups_by_source):
        groups = groups_by_source[src]
        if src in ALL_HELDOUT:
            heldout.update(groups)
            continue
        # stratify by type signature
        buckets: dict[tuple, list[str]] = collections.defaultdict(list)
        for g, types in groups.items():
            buckets[tuple(sorted(types))].append(g)
        target = max(MIN_GROUPS.get(src, 1), round(len(groups) * fraction))
        picked: list[str] = []
        for sig in sorted(buckets):
            members = sorted(buckets[sig])
            rng.shuffle(members)
            n = len(members) * target / len(groups)
            k = math.floor(n + rng.random())  # stochastic rounding keeps the total near target
            picked.extend(members[:k])
        # top up / trim to the exact target, deterministically
        rest = sorted(set(groups) - set(picked))
        rng.shuffle(rest)
        while len(picked) < target and rest:
            picked.append(rest.pop())
        heldout.update(sorted(picked)[:target] if len(picked) > target else picked)
    return heldout


def files_on_disk_for(groups: set[str]) -> list[str]:
    """Every dataset file belonging to a held-out group (twins and sibling views included)."""
    out = []
    data = DATASET_ROOT / "data"
    wanted_sources = {g.split("/", 1)[0] for g in groups}
    for src in sorted(wanted_sources):
        for p in (data / src).rglob("*"):
            if not p.is_file() or p.name == "LICENSE.md":
                continue
            rel = "data/" + p.relative_to(data).as_posix()
            if group_key(rel) in groups:
                out.append(rel)
    return sorted(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--fraction", type=float, default=FRACTION)
    ap.add_argument("--no-disk-scan", action="store_true", help="list only question paths, skip twin files")
    args = ap.parse_args()

    qs = load_questions()
    heldout = choose_heldout(qs, args.fraction, args.seed)

    if args.no_disk_scan:
        files = sorted({q["path"] for q in qs if group_key(q["path"]) in heldout})
    else:
        files = files_on_disk_for(heldout)

    SPLITS_DIR.mkdir(parents=True, exist_ok=True)
    header = [
        "# BlueprintTrace C1: drawing-level held-out split. One dataset-relative path per line.",
        f"# seed={args.seed} fraction={args.fraction} groups={len(heldout)} files={len(files)}",
        "# Test any path with model.common.is_heldout(path); it collapses pdf/dxf/png twins and IFC views.",
        "# Generated by: python -m model.make_split. Do not hand-edit; re-run instead.",
    ]
    HELDOUT_PATH.write_text("\n".join(header + files) + "\n", encoding="utf-8", newline="\n")

    # summary by source x type
    summ = collections.defaultdict(lambda: {"train_q": 0, "heldout_q": 0, "train_drawings": set(), "heldout_drawings": set()})
    for q in qs:
        g = group_key(q["path"])
        side = "heldout" if g in heldout else "train"
        k = f"{source_of(q['path'])}/{q['type']}"
        summ[k][f"{side}_q"] += 1
        summ[k][f"{side}_drawings"].add(g)
    summary = {
        k: {
            "train_q": v["train_q"],
            "heldout_q": v["heldout_q"],
            "train_groups": len(v["train_drawings"]),
            "heldout_groups": len(v["heldout_drawings"]),
        }
        for k, v in sorted(summ.items())
    }
    (SPLITS_DIR / "split_summary.json").write_text(
        json.dumps({"seed": args.seed, "fraction": args.fraction, "by_source_type": summary}, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"held-out groups: {len(heldout)}  files listed: {len(files)}  -> {HELDOUT_PATH}")
    for k, v in summary.items():
        print(f"  {k:28s} train {v['train_q']:6d} q / {v['train_groups']:5d} dr   heldout {v['heldout_q']:5d} q / {v['heldout_groups']:4d} dr")


if __name__ == "__main__":
    main()
